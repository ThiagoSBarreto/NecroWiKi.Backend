CREATE TABLE IF NOT EXISTS `NecroWiKi`.`PORTAL_ACCOUNTS` (
    `ID` char(36) NOT NULL,
    `USERNAME` varchar(32) NOT NULL,
    `NORMALIZED_USERNAME` varchar(32) NOT NULL,
    `PASSWORD_HASH` varchar(255) NOT NULL,
    `ROLE` varchar(16) NOT NULL,
    `IS_ACTIVE` bit NOT NULL,
    `CREATED_AT_UTC` datetime(6) NOT NULL,
    CONSTRAINT `PORTAL_ACCOUNTS_PK` PRIMARY KEY (`ID`),
    CONSTRAINT `PORTAL_ACCOUNTS_ROLE_CK` CHECK (`ROLE` IN ('Admin', 'User')),
    CONSTRAINT `PORTAL_ACCOUNTS_USERNAME_UQ` UNIQUE (`NORMALIZED_USERNAME`)
)
ENGINE=InnoDB
DEFAULT CHARSET=utf8mb4
COLLATE=utf8mb4_unicode_ci;